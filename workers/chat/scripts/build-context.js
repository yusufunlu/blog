#!/usr/bin/env node
/*
  Walks the Gatsby blog, pulls (title, date, spoiler) from every English
  index.md, loads the resume text, and emits workers/chat/src/context.js.

  Run from anywhere:
    node workers/chat/scripts/build-context.js
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.resolve(__dirname, '..', '..', '..');
const PAGES_DIR = path.join(ROOT, 'src', 'pages');
const RESUME_PATH = path.join(__dirname, '..', 'resume.txt');
const OUT_PATH = path.join(__dirname, '..', 'src', 'context.js');
const BLOG_URL = 'https://yusufunlu.github.io/blog';

function parseFrontmatter(src) {
  const match = src.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const out = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^([A-Za-z_][\w-]*)\s*:\s*(.*)$/);
    if (!m) continue;
    let value = m[2].trim();
    if (
      (value.startsWith("'") && value.endsWith("'")) ||
      (value.startsWith('"') && value.endsWith('"'))
    ) {
      value = value.slice(1, -1);
    }
    out[m[1]] = value;
  }
  return out;
}

function collectPosts() {
  const entries = fs.readdirSync(PAGES_DIR, { withFileTypes: true });
  const posts = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const mdPath = path.join(PAGES_DIR, entry.name, 'index.md');
    if (!fs.existsSync(mdPath)) continue;
    const raw = fs.readFileSync(mdPath, 'utf8');
    const fm = parseFrontmatter(raw);
    if (!fm.title) continue;
    posts.push({
      title: fm.title,
      date: fm.date || '',
      spoiler: fm.spoiler || '',
    });
  }
  posts.sort((a, b) => (a.date < b.date ? 1 : -1));
  return posts;
}

const resume = fs.readFileSync(RESUME_PATH, 'utf8').trim();
const posts = collectPosts();

const output = `// AUTO-GENERATED by workers/chat/scripts/build-context.js
// Re-run that script after editing resume.txt or adding/removing blog posts.
export const BLOG_URL = ${JSON.stringify(BLOG_URL)};

export const RESUME = ${JSON.stringify(resume)};

export const POSTS = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(OUT_PATH, output);
console.log(
  `Wrote ${OUT_PATH} (${posts.length} posts, ${resume.length} chars of resume).`
);
